    initializeFutureSeasonPanels();
    refreshHorizontalCarouselControls = initializeHorizontalCarouselControls();
    initializeSeasonDateLabels();

    liga.addEventListener("click", (event) => {
      const target = event.target instanceof Element ? event.target : null;
      if (!target) return;

      const detailToggle = target.closest("[data-toggle-detail]");
      if (detailToggle && liga.contains(detailToggle)) {
        toggleDetail(detailToggle.dataset.toggleDetail);
        return;
      }

      const seasonButton = target.closest(".season-btn");
      if (seasonButton && liga.contains(seasonButton)) {
        const seasonTarget = Number(seasonButton.dataset.seasonTarget);
        const hasSeasonPanel = liga.querySelector(`#season${seasonTarget}`);
        if (seasonButton.classList.contains("season-btn-upcoming") && !hasSeasonPanel) {
          if (lockedNotice) {
            lockedNotice.textContent = seasonButton.dataset.startText || "";
            lockedNotice.hidden = false;
          }
        } else {
          if (lockedNotice) lockedNotice.hidden = true;
          showSeason(seasonTarget);
        }
        return;
      }

      const pageArrow = target.closest(".angkatan-carousel-arrow");
      if (pageArrow && liga.contains(pageArrow)) {
        changeAngkatanPage(Number(pageArrow.dataset.angkatanDirection));
        return;
      }

      const standingsButton = target.closest("[data-open-standings]");
      if (standingsButton && liga.contains(standingsButton)) {
        openStandings(Number(standingsButton.dataset.openStandings));
      }
    });

    initializeOfficialMemberRosters();
    initializeStandings();
    initializeSeasonIntros();
    changeAngkatanPage(0);
